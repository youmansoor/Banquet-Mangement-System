<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;

class TenantSetting extends Model
{
    protected $fillable = [
        'tenant_id',

        /*
        |--------------------------------------------------------------------------
        | BUSINESS
        |--------------------------------------------------------------------------
        */

        'business_name',
        'business_phone',
        'business_email',
        'business_address',

        /*
        |--------------------------------------------------------------------------
        | TAX
        |--------------------------------------------------------------------------
        */

        'tax_enabled',
        'tax_name',
        'tax_percentage',
        'taxes',

        /*
        |--------------------------------------------------------------------------
        | GENERAL
        |--------------------------------------------------------------------------
        */

        'currency',

        /*
        |--------------------------------------------------------------------------
        | PAYMENT
        |--------------------------------------------------------------------------
        */

        'payment_method',
        'booking_advance_percentage',
        'payment_rules',

        /*
        |--------------------------------------------------------------------------
        | INSTALLMENT OPTIONS
        |--------------------------------------------------------------------------
        */

        'installment_options',
    ];

    protected $casts = [
        /*
        |--------------------------------------------------------------------------
        | TAX
        |--------------------------------------------------------------------------
        */

        'tax_enabled' => 'boolean',

        'tax_percentage' => 'decimal:2',

        'taxes' => 'array',

        /*
        |--------------------------------------------------------------------------
        | PAYMENT
        |--------------------------------------------------------------------------
        */

        'booking_advance_percentage' => 'decimal:2',

        'payment_rules' => 'array',

        /*
        |--------------------------------------------------------------------------
        | INSTALLMENTS
        |--------------------------------------------------------------------------
        */

        'installment_options' => 'array',
    ];

    public function tenant()
    {
        return $this->belongsTo(
            Tenant::class
        );
    }
}