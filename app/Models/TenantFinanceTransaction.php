<?php

namespace App\Models;

use App\Models\Vendor;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;

class TenantFinanceTransaction extends Model
{
    protected $table = 'tenant_finance_transactions';


    protected $fillable = [

        'tenant_id',

        /*
        |--------------------------------------------------------------------------
        | HARD-CODED TRANSACTION TYPE
        |--------------------------------------------------------------------------
        |
        | customer_payment
        | vendor_payment
        | banquet_expense
        |
        */

        'transaction_type',

        /*
        |--------------------------------------------------------------------------
        | PAYMENT CATEGORY
        |--------------------------------------------------------------------------
        */

        'payment_category_id',


        /*
        |--------------------------------------------------------------------------
        | BENEFICIARY / VENDOR
        |--------------------------------------------------------------------------
        */

        'beneficiary_id',
        'vendor_id',


        /*
        |--------------------------------------------------------------------------
        | CUSTOMER
        |--------------------------------------------------------------------------
        */

        'customer_id',
        'booking_id',
        'invoice_id',


        /*
        |--------------------------------------------------------------------------
        | SNAPSHOT REFERENCES
        |--------------------------------------------------------------------------
        */

        'job_number',
        'bill_number',


        /*
        |--------------------------------------------------------------------------
        | DESCRIPTION
        |--------------------------------------------------------------------------
        */

        'item_description',


        /*
        |--------------------------------------------------------------------------
        | VENDOR DOCUMENT
        |--------------------------------------------------------------------------
        */

        'vendor_invoice',


        /*
        |--------------------------------------------------------------------------
        | BANK
        |--------------------------------------------------------------------------
        */

        'tenant_bank_id',


        /*
        |--------------------------------------------------------------------------
        | CHEQUE
        |--------------------------------------------------------------------------
        */

        'cheque_number',
        'cheque_date',


        /*
        |--------------------------------------------------------------------------
        | DEBIT / CREDIT
        |--------------------------------------------------------------------------
        */

        'transaction_direction',


        /*
        |--------------------------------------------------------------------------
        | AMOUNT
        |--------------------------------------------------------------------------
        */

        'amount',


        /*
        |--------------------------------------------------------------------------
        | DATE
        |--------------------------------------------------------------------------
        */

        'transaction_date',


        /*
        |--------------------------------------------------------------------------
        | REMARKS
        |--------------------------------------------------------------------------
        */

        'remarks',

    ];


    protected $casts = [

        'amount' => 'decimal:2',

        'transaction_date' => 'date',

        'cheque_date' => 'date',

    ];


    /*
    |--------------------------------------------------------------------------
    | TENANT
    |--------------------------------------------------------------------------
    */

    public function tenant(): BelongsTo
    {
        return $this->belongsTo(
            Tenant::class,
            'tenant_id'
        );
    }


    /*
    |--------------------------------------------------------------------------
    | PAYMENT CATEGORY
    |--------------------------------------------------------------------------
    */

    public function paymentCategory(): BelongsTo
    {
        return $this->belongsTo(
            TenantFinanceMaster::class,
            'payment_category_id'
        );
    }


    /*
    |--------------------------------------------------------------------------
    | BENEFICIARY
    |--------------------------------------------------------------------------
    */

    public function beneficiary(): BelongsTo
    {
        return $this->belongsTo(
            TenantFinanceMaster::class,
            'beneficiary_id'
        );
    }


    /*
    |--------------------------------------------------------------------------
    | VENDOR
    |--------------------------------------------------------------------------
    */

    public function vendor(): BelongsTo
    {
        return $this->belongsTo(
            Vendor::class,
            'vendor_id'
        );
    }


    /*
    |--------------------------------------------------------------------------
    | CUSTOMER
    |--------------------------------------------------------------------------
    */

    public function customer(): BelongsTo
    {
        return $this->belongsTo(
            Customer::class,
            'customer_id'
        );
    }


    /*
    |--------------------------------------------------------------------------
    | BOOKING
    |--------------------------------------------------------------------------
    */

    public function booking(): BelongsTo
    {
        return $this->belongsTo(
            Booking::class,
            'booking_id'
        );
    }


    /*
    |--------------------------------------------------------------------------
    | INVOICE
    |--------------------------------------------------------------------------
    */

    public function invoice(): BelongsTo
    {
        return $this->belongsTo(
            Invoice::class,
            'invoice_id'
        );
    }


    /*
    |--------------------------------------------------------------------------
    | TENANT BANK
    |--------------------------------------------------------------------------
    */

    public function tenantBank(): BelongsTo
    {
        return $this->belongsTo(
            TenantBank::class,
            'tenant_bank_id'
        );
    }
}